export const SUPPORTED_LANGUAGES = Object.freeze(Object.keys(MESSAGES));

export function translator(language = "en") {
  const catalog = MESSAGES[language] || MESSAGES.en;
  return (key, values = {}) => catalog[key].replace(/\{([a-z]+)\}/g, (_, name) => String(values[name]));
}
